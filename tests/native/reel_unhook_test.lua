local game_cfg = require("common.game_cfg")
local host = require("tests.support.fishing_host")

describe("收线脱钩与生命周期（server_runtime）", function()
  local env
  after_each(function() if env then env:dispose() env = nil end end)

  local function hooked()
    env:cast()
    env:hook()
    return env:last_state().reelSession
  end

  it("test_zero_progress_unhooks_and_destroys_line", function()
    env = host.new()
    hooked()
    env:advance(10.19)
    assert.are.equal("idle", env:last_state().phase)
    assert.are.equal(0, env:alive_units("CastLine_"))
    assert.are.equal(0, env:alive_units("LandedFish_"))
  end)

  it("test_manual_reel_back_does_not_spawn_fish", function()
    env = host.new()
    local session = hooked()
    env:close(session)
    assert.are.equal("idle", env:last_state().phase)
    assert.are.equal(0, env:alive_units("LandedFish_"))
  end)

  it("test_downed_tears_down_hooked_session_and_line", function()
    env = host.new()
    hooked()
    env.runtime.life:ApplyDamage(env.player, game_cfg.vitals.MaxHealth)
    assert.are.equal("idle", env:last_state().phase)
    assert.are.equal(0, env:alive_units("CastLine_"))
  end)

  it("test_leave_tears_down_line_before_rejoin", function()
    env = host.new()
    hooked()
    env.runtime:on_player_removing(env.player)
    assert.are.equal(0, env:alive_units("CastLine_"))
  end)

  it("test_paralysis_blocks_click_without_immediate_unhook", function()
    env = host.new()
    local session = hooked()
    local tree = env.runtime:get_player_tree(env.player.UserId)
    assert.is_true(tree:apply_modifier("paralyze", { duration = 0.4 }))
    local before = #env:reel_replies()
    env:click(session, 1, 1)
    assert.are.equal(before, #env:reel_replies())
    assert.are.equal("hooked", env:last_state().phase)
    env:advance(0.4)
    env:click(session, 1, 2)
    assert.are.equal(1, env:reel_replies()[#env:reel_replies()].accepted)
  end)

  it("test_unhooked_state_is_not_a_landed_result", function()
    env = host.new()
    local session = hooked()
    env:close(session)
    assert.are.equal(0, #env.compendium)
    for _, fact in ipairs(env.quests) do assert.are_not.equal("Land", fact.kind) end
  end)
end)
