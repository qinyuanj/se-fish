local host = require("tests.support.reel_view_host")

describe("客户端收线状态机（reel_overlay_view）", function()
  local env
  after_each(function() if env then env:dispose() env = nil end end)

  it("test_ended_session_ignores_late_started_echo", function()
    env = host.new()
    env:hook("s1")
    env.reel.close("s1")
    env.writer:ingest_event("ReelInRE", { action = "started", session = "s1", progress = 50 })
    assert.is_nil(env:child("ReelMask"))
    assert.is_nil(env.reel.click)
    env.clock:advance(0.1)
    assert.are.equal(0, #env.sent)
  end)

  it("test_heartbeat_collects_after_hundred_ms", function()
    env = host.new()
    env:hook("s1")
    env.reel.click("s1")
    env.reel.click("s1")
    env.clock:advance(0.1)
    assert.are.same({ s = "s1", n = 2, q = 1 }, env.sent[1])
    env.clock:advance(0.1)
    assert.are.equal(1, #env.sent)
  end)

  it("test_snapshot_does_not_reset_pending_and_close_flushes_first", function()
    env = host.new()
    env:hook("s1")
    env.reel.click("s1")
    env.writer:ingest_event("CastState", { phase = "hooked", reelSession = "s1", castId = 1 })
    env.reel.close("s1")
    assert.are.same({ s = "s1", n = 1, q = 1 }, env.sent[1])
    assert.are.same({ session = "s1" }, env.closed[1])
    assert.are.equal(1, #env.sent)
  end)

  it("test_replacing_session_clears_pending_and_uses_one_clean_window", function()
    env = host.new()
    env:hook("s1")
    env.reel.click("s1")
    env:hook("s2", 2)
    env.reel.click("s2")
    env.clock:advance(0.1)
    assert.are.equal(1, #env.sent)
    assert.are.same({ s = "s2", n = 1, q = 1 }, env.sent[1])
  end)

  it("test_no_batching_heartbeat_until_a_live_session_exists", function()
    env = host.new()
    env.clock:advance(1)
    assert.are.equal(0, #env.sent)
    env:hook("s1")
    env.clock:advance(1)
    assert.are.equal(0, #env.sent)
  end)

  it("test_close_without_pending_sends_no_empty_batch", function()
    env = host.new()
    env:hook("s1")
    env.reel.close("s1")
    assert.are.equal(0, #env.sent)
    assert.are.equal(1, #env.closed)
  end)
end)
