local game_cfg = require("common.game_cfg")
local host = require("tests.support.fishing_host")

describe("抛竿与等待上钩（server_runtime）", function()
  local env
  after_each(function() if env then env:dispose() env = nil end end)

  it("test_valid_cast_consumes_one_bait_and_waits_for_hook_delay", function()
    env = host.new({ roll = 1, multiplier_roll = 150 })
    local before = env.data.data.Bait[game_cfg.Items.Id.Worm]
    env:cast()
    assert.are.equal("cast", env:last_state().phase)
    assert.are.equal(before - 1, env.data.data.Bait[game_cfg.Items.Id.Worm])
    env:advance(game_cfg.Casting.HookDelaySec - 0.01)
    assert.are.equal("cast", env:last_state().phase)
    env:advance(0.01)
    assert.are.equal("hooked", env:last_state().phase)
    assert.are.equal("tilapia", env:last_state().fishId)
    assert.are.equal(1, env.quests[1].kind == "CastWater" and 1 or 0)
  end)

  it("test_cooldown_rejects_before_bait_consumption", function()
    env = host.new({ cooldown = true })
    local before = env.data:ItemCount(game_cfg.Items.Id.Worm)
    env:cast()
    assert.are.equal("idle", env:last_state().phase)
    assert.are.equal("cooldown", env:last_state().result.reason)
    assert.are.equal(before, env.data:ItemCount(game_cfg.Items.Id.Worm))
  end)

  it("test_already_casting_rejects_without_second_bait", function()
    env = host.new()
    env:cast()
    local before = env.data:ItemCount(game_cfg.Items.Id.Worm)
    env:cast()
    assert.are.equal("alreadyCasting", env:last_state().result.reason)
    assert.are.equal(before, env.data:ItemCount(game_cfg.Items.Id.Worm))
    assert.are.equal(1, env:alive_units("CastLine_"))
  end)

  it("test_invalid_rod_and_missing_bait_are_rejected", function()
    env = host.new({ bait = false })
    env:cast({ action = "Cast", slot = 1, itemId = "not-a-rod" })
    assert.are.equal("invalidRod", env:last_state().result.reason)
    env:cast()
    assert.are.equal("cast", env:last_state().phase)
  end)

  it("test_downed_player_cannot_cast", function()
    env = host.new()
    env.runtime.life:ApplyDamage(env.player, game_cfg.vitals.MaxHealth)
    env:cast()
    assert.is_nil(env:last_state())
    assert.are.equal(0, env:alive_units("CastLine_"))
  end)

  it("test_invalid_landing_does_not_create_line_or_consume_bait", function()
    env = host.new({ position = { x = 0, y = 2, z = 0 } })
    local before = env.data:ItemCount(game_cfg.Items.Id.Worm)
    env:cast()
    assert.are.equal("invalidLanding", env:last_state().result.reason)
    assert.are.equal(before, env.data:ItemCount(game_cfg.Items.Id.Worm))
    assert.are.equal(0, env:alive_units("CastLine_"))
  end)

  it("test_reel_waiting_clears_session_and_allows_recast", function()
    env = host.new()
    env:cast()
    env:reel_back()
    assert.are.equal("idle", env:last_state().phase)
    assert.are.equal(0, env:alive_units("CastLine_"))
    env:cast()
    assert.are.equal("cast", env:last_state().phase)
  end)

  it("test_request_cast_state_returns_current_public_snapshot", function()
    env = host.new()
    env:cast()
    env:request()
    assert.are.equal("cast", env:last_state().phase)
    assert.are.equal(1, env:last_state().castId)
  end)

  it("test_spawn_failure_does_not_duplicate_landing_effects", function()
    env = host.new({ spawn_fails = true })
    env:cast()
    env:hook()
    local session = env:last_state().reelSession
    env:click(session, 10, 1)
    env:advance(1)
    env:click(session, 10, 2)
    assert.are.equal("landed", env:last_state().phase)
    assert.are.equal(0, env:alive_units("LandedFish_"))
    assert.are.equal(1, #env.compendium)
  end)

  it("test_debug_set_next_fish_updates_hooked_snapshot", function()
    env = host.new()
    assert.is_true(env.runtime:set_next_fish(env.player, "carp"))
    env:cast()
    env:hook()
    assert.are.equal("carp", env:last_state().fishId)
  end)
end)
