-- tests.support.fs_fixture 自测：仓库根、临时目录、落盘助手、列目录、PATH 查找。
local fs = require("tests.support.fs_fixture")

local BS = string.char(92)

describe("TestFsFixtureRepoRoot", function()
  it("points at the repository root that holds .busted", function()
    local root = fs.repo_root()
    assert.is_not_nil(root)
    assert.is_nil(root:find(BS, 1, true), "仓库根应归一为正斜杠")
    assert.is_true(fs.exists(root .. "/.busted"))
    assert.is_true(fs.exists(root .. "/AGENTS.md"))
  end)
end)

describe("TestFsFixtureTempAndFiles", function()
  it("creates a unique temp directory under the repo", function()
    local a = fs.temp_dir()
    local b = fs.temp_dir()
    assert.is_true(fs.exists(a))
    assert.are_not.equal(a, b)
    assert.is_truthy(a:find(fs.repo_root(), 1, true))
  end)

  it("writes, slurps and lists files", function()
    local dir = fs.temp_dir()
    fs.write_file(dir .. "/nested/deep/x.txt", "内容")
    fs.write_file(dir .. "/a.txt", "A")
    assert.are.equal("内容", fs.slurp(dir .. "/nested/deep/x.txt"))
    local names = fs.list_dir(dir)
    assert.are.same({ "a.txt", "nested" }, names)
  end)

  it("mkdirp and rmrf remove a tree", function()
    local dir = fs.temp_dir()
    fs.mkdirp(dir .. "/p/q")
    assert.is_true(fs.exists(dir .. "/p/q"))
    fs.rmrf(dir .. "/p")
    assert.is_false(fs.exists(dir .. "/p"))
  end)
end)

describe("TestFsFixtureFindOnPath", function()
  it("finds an executable present on PATH and misses an absent one", function()
    local lua = fs.find_on_path("lua")
    assert.is_not_nil(lua)
    assert.is_nil(fs.find_on_path("definitely-not-a-real-tool-xyz"))
  end)
end)
