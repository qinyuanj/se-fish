-- 收线覆盖层表现：#302 RootView / EUI 节点接缝。
local Host = require("tests.support.reel_view_host")

describe("收线界面表现（RootView × ReelOverlayView）", function()
  local env
  after_each(function() if env then env:dispose() env = nil end end)

  it("test_click_feedback_and_smooth_chase_on_the_bar", function()
    env = Host.new()
    env:hook("s1")
    assert.are.equal(50, env:child("ReelBar").Percent)
    env.reel.click("s1")
    env.clock:advance(0.1)
    assert.are.same({ s = "s1", n = 1, q = 1 }, env.sent[1])
    env.writer:ingest_event("ReelInRE", { action = "progress", session = "s1", progress = 55, q = 1 })
    assert.are.equal(55, env:child("ReelBar").Percent)
  end)

  it("test_empty_draw_clears_waiting_and_recast_replaces_feedback", function()
    env = Host.new()
    env.writer:ingest_event("CastState", { phase = "cast", castId = 1, landing = { x = 1, y = 2, z = 3 } })
    assert.is_nil(env:child("ReelMask"))
    env:hook("s1")
    assert.is_not_nil(env:child("ReelMask"))
    env.writer:ingest_event("CastState", { phase = "unhooked", castId = 1 })
    assert.is_nil(env:child("ReelMask"))
    env:hook("s2", 2)
    assert.is_not_nil(env:child("ReelMask"))
  end)

  it("test_landed_greys_out_action_by_closing_overlay", function()
    env = Host.new()
    env:hook("s1")
    env.writer:ingest_event("CastState", { phase = "landed", castId = 1, fishId = "tilapia" })
    assert.is_nil(env:child("ReelMask"))
    assert.is_true(env.created[1].Destroyed)
  end)

  it("test_death_closes_overlay_and_reopen_requires_new_session", function()
    env = Host.new()
    env:hook("s1")
    env.writer:ingest_event("SurvivalState", { phase = "downed" })
    assert.is_nil(env:child("ReelMask"))
    env.writer:ingest_event("CastState", { phase = "hooked", reelSession = "s1", castId = 1 })
    assert.is_nil(env:child("ReelMask"))
    env.writer:ingest_event("SurvivalState", { phase = "alive" })
    env:hook("s2", 2)
    assert.is_not_nil(env:child("ReelMask"))
  end)

  it("test_reopen_restores_new_session_without_stale_nodes", function()
    env = Host.new()
    env:hook("s1")
    env.reel.close("s1")
    assert.is_nil(env:child("ReelMask"))
    env:hook("s2", 2)
    assert.is_not_nil(env:child("ReelMask"))
    env.root:Destroy()
    assert.are.equal(0, env:alive())
  end)

  it("test_unhooked_phase_reels_back_without_showing_the_bar", function()
    env = Host.new()
    env:hook("s1")
    env.writer:ingest_event("ReelInRE", { action = "unhooked", session = "s1", progress = 0 })
    assert.is_nil(env:child("ReelMask"))
    assert.are.equal(0, env:alive())
  end)
end)
