local GameCfg = require("common.game_cfg")
local Host = require("tests.support.fishing_host")

describe("首领饵必出首领（ServerRuntime × PlayerData）", function()
  local env
  after_each(function() if env then env:dispose() env = nil end end)

  it("test_cast_consumes_duck_and_never_returns_it", function()
    env = Host.new({ bait = "duck", bait_count = 1 })
    env:cast()
    assert.are.equal(0, env.data:ItemCount("duck"))
    assert.is_nil(env.data.Data.selected_bait)
    env:hook()
    assert.are.equal("alligatorGar", env:last_state().fishId)
    env:reel_back()
    assert.are.equal(0, env.data:ItemCount("duck"))
  end)

  it("test_config_pins", function()
    assert.are.equal("alligatorGar", GameCfg.Casting.BossBait.duck)
    assert.are.equal("fish16Boss", GameCfg.Casting.BossBait.item121)
    assert.are.equal(0.12, GameCfg.Casting.ActionCooldownSec)
    assert.are.equal(3, GameCfg.Casting.HookDelaySec)
  end)

  it("test_consume_duck_takes_itembar_before_backpack", function()
    env = Host.new({ bait = false })
    assert(env.data:AddItem("duck", 1))
    assert(env.data:SelectBait("duck"))
    local ok, bait = env.data:ConsumeSelectedBait()
    assert.is_true(ok)
    assert.are.equal("duck", bait)
    assert.are.equal(0, env.data:ItemCount("duck"))
  end)

  it("test_duck_hook_always_alligator_gar_ignoring_table_and_rod", function()
    env = Host.new({ bait = "duck", roll = 999, multiplier_roll = 200 })
    env:cast()
    env:hook()
    assert.are.equal("alligatorGar", env:last_state().fishId)
  end)

  it("test_pearl_hooks_dragon_in_every_water_and_abort_does_not_refund", function()
    env = Host.new({ bait = "item121", bait_count = 1 })
    env:cast()
    env:hook()
    assert.are.equal("fish16Boss", env:last_state().fishId)
    env:reel_back()
    assert.are.equal(0, env.data:ItemCount("item121"))
  end)

  it("test_select_duck_requires_duck_in_storage", function()
    env = Host.new({ bait = false })
    assert.is_false(env.data:SelectBait("duck"))
    assert(env.data:AddItem("duck", 1))
    assert.is_true(env.data:SelectBait("duck"))
  end)

  it("test_snapshot_lists_duck_count_alongside_worm", function()
    env = Host.new({ bait = "duck", bait_count = 1 })
    local snapshot = env.data:GetItemBarSnapshot()
    assert.are.equal(1, snapshot.bait.duck)
    assert.are.equal("duck", snapshot.selectedBait)
  end)

  it("test_worm_hook_still_draws_from_zone_table", function()
    env = Host.new({ roll = 1, multiplier_roll = 150 })
    env:cast()
    env:hook()
    assert.are.equal("tilapia", env:last_state().fishId)
    assert.are.equal(1.5, env:last_state().mult)
  end)
end)
