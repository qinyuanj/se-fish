-- 收线会话、限频与重复包：#302 公共 RemoteEvent 接缝。
local Host = require("tests.support.fishing_host")

describe("收线会话管理（ServerRuntime）", function()
  local env
  after_each(function() if env then env:dispose() env = nil end end)

  local function begin()
    env:cast()
    env:hook()
    return env:last_state().reelSession
  end

  it("test_click_batch_advances_progress_and_replies_once", function()
    env = Host.new()
    local session = begin()
    env:click(session, 2, 7)
    local replies = env:reel_replies()
    assert.are.equal("progress", replies[#replies].action)
    assert.are.equal(2, replies[#replies].accepted)
    assert.are.equal(7, replies[#replies].q)
    assert.are.equal(60, replies[#replies].progress)
  end)

  it("test_stale_session_and_bad_payload_are_ignored", function()
    env = Host.new()
    local session = begin()
    local before = #env:reel_replies()
    env:click("wrong", 1, 1)
    env.channel("ReelInRE").OnServerEvent:Fire(env.player, { s = session, n = -1, q = 2 })
    assert.are.equal(before, #env:reel_replies())
    assert.are.equal("hooked", env:last_state().phase)
  end)

  it("test_rate_limit_clamps_a_burst_to_ten_clicks", function()
    env = Host.new()
    local session = begin()
    env:click(session, 11, 1)
    assert.are.equal("landed", env:last_state().phase)
  end)

  it("test_close_unhooks_and_duplicate_close_is_idempotent", function()
    env = Host.new()
    local session = begin()
    env:close(session)
    local states = #env:states()
    env:close(session)
    assert.are.equal(states, #env:states())
    assert.are.equal("idle", env:last_state().phase)
    assert.are.equal(0, env:alive_units("CastLine_"))
  end)

  it("test_clock_decay_is_one_hertz", function()
    env = Host.new()
    begin()
    env:advance(2)
    assert.are.equal(40, env:reel_replies()[#env:reel_replies()].progress)
  end)

  it("test_grace_accepts_inflight_batch_but_late_batch_unhooks", function()
    env = Host.new()
    local session = begin()
    env:advance(10.17)
    env:click(session, 2, 1)
    assert.are.equal("hooked", env:last_state().phase)
    env:close(session)
    session = begin()
    env:advance(10.201)
    env:click(session, 10, 1)
    assert.are.equal("idle", env:last_state().phase)
  end)
end)
